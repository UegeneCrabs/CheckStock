(function () {
    var form = document.querySelector('[data-week-update-form]');
    if (!form) return;
    var status = form.querySelector('[data-week-status]');
    var run = form.querySelector('[data-week-run]');
    var search = form.querySelector('[data-week-search]');
    var searchStatus = form.querySelector('[data-week-search-status]');
    var sales = form.querySelector('[data-week-sales]');
    var salesStatus = form.querySelector('[data-week-sales-status]');
    var stock = form.querySelector('[data-week-stock]');
    var stockStatus = form.querySelector('[data-week-stock-status]');
    var submit = form.querySelectorAll('[type="submit"]');
    var unsaved = form.querySelector('[data-week-unsaved]');
    var saveStatus = form.querySelector('[data-week-save-status]');
    var saved = !run.disabled;
    var dirty = false;
    var busy = false;
    var savedValues = values();
    var resultMarkup = new WeakMap();
    var lastSearchError = '';

    function values() {
        return JSON.stringify(Array.from(form.querySelectorAll('input, select'), function (input) {
            return [input.name, input.type === 'checkbox' ? input.checked : input.value];
        }));
    }

    function controls() {
        run.disabled = busy || dirty || !saved;
        search.disabled = busy || dirty || !saved;
        sales.disabled = busy || dirty || !saved;
        stock.disabled = busy || dirty || !saved;
        submit.forEach(function (button) { button.disabled = busy; });
        unsaved.hidden = !dirty;
        saveStatus.hidden = dirty && !saveStatus.classList.contains('export-status--error');
        [run, search, sales, stock].forEach(function (button) {
            button.title = dirty || !saved ? 'Сначала сохраните настройки' : '';
        });
    }
    function show(message, error) {
        status.textContent = message;
        status.classList.toggle('export-status--error', Boolean(error));
    }
    function showSave(message, error) {
        saveStatus.textContent = message;
        saveStatus.classList.toggle('export-status--error', Boolean(error));
        saveStatus.hidden = false;
    }
    function replaceResult(selector, markup) {
        var container = form.querySelector(selector);
        // Do not collapse details, reset scroll or move focus on each status refresh.
        if (resultMarkup.get(container) === markup) return;
        var open = Array.from(container.querySelectorAll('details[open]'), function (detail) {
            return detail.querySelector('summary').textContent;
        });
        // Generated by our server; spreadsheet strings are HTML-escaped there.
        container.innerHTML = markup;
        resultMarkup.set(container, markup);
        container.querySelectorAll('details').forEach(function (detail) {
            detail.open = open.includes(detail.querySelector('summary').textContent);
        });
    }
    function apply(data) {
        form.querySelector('[data-week-value]').textContent = data.value;
        form.querySelector('[data-week-schedule]').textContent = data.schedule_text;
        show(data.status_text, data.has_error);
        form.querySelector('[data-week-search-schedule]').textContent = data.search_schedule_text;
        searchStatus.textContent = data.search_status_text;
        searchStatus.classList.toggle('export-status--error', Boolean(data.search_has_error));
        replaceResult('[data-week-search-results]', data.search_html);
        form.querySelector('[data-week-sales-schedule]').textContent = data.sales_schedule_text;
        salesStatus.textContent = data.sales_status_text;
        salesStatus.classList.toggle('export-status--error', Boolean(data.sales_has_error));
        replaceResult('[data-week-sales-results]', data.sales_html);
        form.querySelector('[data-week-stock-schedule]').textContent = data.stock_schedule_text;
        stockStatus.textContent = data.stock_status_text;
        stockStatus.classList.toggle('export-status--error', Boolean(data.stock_has_error));
        replaceResult('[data-week-stock-results]', data.stock_html);
        revealSearchError();
    }
    function revealSearchError() {
        var error = searchStatus.classList.contains('export-status--error') ? searchStatus.textContent : '';
        if (error && error !== lastSearchError) {
            form.querySelector('[data-week-search-panel]').open = true;
        }
        lastSearchError = error;
    }
    ['input', 'change'].forEach(function (event) {
        form.addEventListener(event, function () {
            dirty = values() !== savedValues;
            saveStatus.classList.remove('export-status--error');
            saveStatus.textContent = saved ? 'Настройки общие для всех действий.' : 'Сначала сохраните настройки.';
            controls();
        });
    });
    async function request(url, body) {
        var response;
        try {
            response = await fetch(url, {
                method: 'POST', body: body,
                headers: { 'X-Requested-With': 'fetch', Accept: 'application/json' },
            });
        } catch (_error) {
            throw new Error('Нет связи с сервером. Проверьте подключение и повторите попытку.');
        }
        var data;
        try { data = await response.json(); }
        catch (_error) { throw new Error('Сервер не смог выполнить запрос. Обновите страницу и повторите попытку.'); }
        if (!response.ok || !data.ok) {
            if (data.search_html !== undefined) apply(data);
            throw new Error(data.error || 'Не удалось выполнить запрос');
        }
        return data;
    }
    async function perform(action, actionStatus, button, busyLabel) {
        busy = true;
        controls();
        var label = button.textContent;
        button.textContent = busyLabel;
        button.setAttribute('aria-busy', 'true');
        // Freeze fields as well: a successful save must correspond to the visible values.
        var inputs = form.querySelectorAll('input, select');
        inputs.forEach(function (input) { input.disabled = true; });
        try { await action(); }
        catch (error) {
            if (actionStatus) {
                actionStatus.textContent = error.message;
                actionStatus.classList.add('export-status--error');
            } else showSave(error.message, true);
        }
        finally {
            inputs.forEach(function (input) { input.disabled = false; });
            button.textContent = label;
            button.removeAttribute('aria-busy');
            busy = false; controls();
        }
    }
    form.addEventListener('submit', function (event) {
        event.preventDefault();
        if (busy) return;
        var body = new FormData(form);
        perform(async function () {
            showSave('Сохраняю настройки…', false);
            var data = await request('/admin/google-week-update', body);
            saved = true; dirty = false;
            savedValues = values();
            apply(data);
            showSave('Настройки сохранены', false);
            form.querySelector('[data-week-sheet-link]').href = body.get('spreadsheet_url');
        }, null, submit[0], 'Сохраняю…');
    });
    run.addEventListener('click', function () {
        if (busy || dirty || !saved) return;
        perform(async function () {
            show('Обновляю неделю в Google Таблице…', false);
            apply(await request('/admin/google-week-update/run', new FormData()));
        }, status, run, 'Обновляю…');
    });
    search.addEventListener('click', function () {
        if (busy || dirty || !saved) return;
        perform(async function () {
            searchStatus.textContent = 'Ищу недельные заголовки в Google Таблице…';
            searchStatus.classList.remove('export-status--error');
            apply(await request('/admin/google-week-update/search', new FormData()));
        }, searchStatus, search, 'Ищу недели…');
    });
    sales.addEventListener('click', function () {
        if (busy || dirty || !saved) return;
        perform(async function () {
            salesStatus.textContent = 'Считаю заказы по неделям и записываю в Google Таблицу…';
            salesStatus.classList.remove('export-status--error');
            apply(await request('/admin/google-week-update/sales', new FormData()));
            form.querySelector('[data-week-sales-report]').open = true;
        }, salesStatus, sales, 'Выгружаю…');
    });
    stock.addEventListener('click', function () {
        if (busy || dirty || !saved) return;
        perform(async function () {
            stockStatus.textContent = 'Читаю снимок FBO на конец недели и записываю в Google Таблицу…';
            stockStatus.classList.remove('export-status--error');
            apply(await request('/admin/google-week-update/stock', new FormData()));
            form.querySelector('[data-week-stock-report]').open = true;
        }, stockStatus, stock, 'Выгружаю…');
    });
    controls();
    revealSearchError();
    // Refresh persisted scheduled results while the card is visible, without touching a dirty form.
    window.setInterval(async function () {
        if (busy || dirty || document.hidden || form.closest('[hidden]')) return;
        try {
            var response = await fetch('/admin/google-week-update', {
                headers: { Accept: 'application/json' }, cache: 'no-store',
            });
            if (response.ok) {
                var data = await response.json();
                if (!busy && !dirty) apply(data);
            }
        } catch (_error) { /* Keep the last visible result on a temporary connection failure. */ }
    }, 30000);
})();
